_STRINGS = {"ru": RU, "en": EN}

# Языки Windows, для которых по умолчанию включается русский: ru, uk, be, kk
_RU_PRIMARY_IDS = {0x19, 0x22, 0x23, 0x3F}


def detect_system_lang() -> str:
    try:
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return "ru" if (lang_id & 0x3FF) in _RU_PRIMARY_IDS else "en"
    except Exception:
        return "en"


def set_lang(lang: str):
    global _lang
    _lang = lang if lang in _STRINGS else detect_system_lang()


def get_lang() -> str:
    return _lang


def t(key: str, **kwargs) -> str:
    text = _STRINGS[_lang].get(key)
    if text is None:
        text = EN.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
